import type {
  CatalogDifficulty,
  CatalogQuestion,
  TestSection,
  TestSubtopic,
  TestTheme,
} from './testCatalog'

type QuestionSpec = [
  text: string,
  correct: string,
  wrong: [string, string, string],
  explanation: string,
  difficulty?: CatalogDifficulty,
]

function questions(prefix: string, specs: QuestionSpec[]): CatalogQuestion[] {
  return specs.map(([text, correct, wrong, explanation, difficulty = 'medium'], index) => ({
    id: `${prefix}-${index + 1}`,
    text,
    options: [correct, ...wrong],
    correctIndex: 0,
    explanation,
    difficulty,
  }))
}

function subtopic(
  id: string,
  slug: string,
  title: string,
  description: string,
  difficulty: CatalogDifficulty,
  specs: QuestionSpec[]
): TestSubtopic {
  return {
    id,
    slug,
    title,
    description,
    difficulty,
    questions: questions(id, specs),
  }
}

function section(
  id: string,
  title: string,
  description: string,
  subtopics: TestSubtopic[]
): TestSection {
  return { id, title, description, subtopics }
}

