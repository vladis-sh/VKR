export const QUIZ_SYSTEM_PROMPT = `Ты генератор вопросов для технических собеседований по программированию и IT.
Создавай вопросы только по темам, связанным с программированием, разработкой ПО, информатикой и смежными техническими областями (языки программирования, фреймворки, базы данных, алгоритмы, структуры данных, сети, операционные системы, DevOps, тестирование, безопасность, системный дизайн и т.п.).
Если запрошенная тема не относится к этим областям — не придумывай вопросы и верни строго JSON {"error": "off_topic"}.
Всегда отвечай только валидным JSON без дополнительного текста.`;

export function buildQuizPrompt(topic: string, count: number, difficulty: string): string {
  const difficultyMap: Record<string, string> = {
    junior: 'начального уровня (junior): базовые концепции',
    middle: 'среднего уровня (middle): практическое применение',
    senior: 'продвинутого уровня (senior): глубокое понимание и edge cases',
  };

  return `Тема: "${topic}".
Сначала реши, относится ли эта тема к программированию, разработке ПО, информатике или смежным техническим областям. Если НЕТ — верни строго JSON {"error": "off_topic"} и больше ничего.

Если тема техническая — создай ${count} вопросов для собеседования по теме "${topic}" уровня ${
    difficultyMap[difficulty] || difficultyMap.junior
  }.

Верни JSON-массив строго в таком формате:
[
  {
    "text": "Текст вопроса",
    "options": ["Вариант A", "Вариант B", "Вариант C", "Вариант D"],
    "correctAnswerIndex": 0,
    "explanation": "Подробное объяснение правильного ответа"
  }
]

Требования:
- Каждый вопрос должен иметь ровно 4 варианта ответа.
- correctAnswerIndex должен быть индексом правильного ответа от 0 до 3.
- Вопросы должны быть технически корректными.
- Объяснения должны быть информативными, 2-4 предложения.
- Все тексты должны быть на русском языке.`;
}
